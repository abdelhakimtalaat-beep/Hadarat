-- قاعدة بيانات المريدين والمرشدين + الصلاحيات
-- شغّله مرة واحدة في Supabase > SQL Editor > Run (بعد access.sql و public-mode.sql)

alter table profiles add column if not exists can_db boolean not null default false;

create table if not exists people(
  id bigint generated by default as identity primary key,
  name text not null,
  birth_date date,
  national_id text,
  phone text,
  governorate text,
  hadra_id bigint references hadarat(id) on delete set null,
  hadra_text text,
  address text,
  murshid_id bigint references people(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists people_murshid_idx on people(murshid_id);
create index if not exists people_hadra_idx on people(hadra_id);
alter table people enable row level security;

create or replace function public.can_db() returns boolean language sql security definer stable set search_path=public
as $$ select public.is_admin() or exists(select 1 from profiles where user_id=auth.uid() and status='approved' and can_db) $$;

drop policy if exists "قراءة قاعدة البيانات" on people;
drop policy if exists "المشرف يكتب قاعدة البيانات" on people;
create policy "قراءة قاعدة البيانات" on people for select to authenticated using (public.can_db());
create policy "المشرف يكتب قاعدة البيانات" on people for all to authenticated using (public.is_admin()) with check (public.is_admin());

alter publication supabase_realtime add table people;
